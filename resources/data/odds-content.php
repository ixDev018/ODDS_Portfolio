# ODDS Knowledge Base

## Mission
ODDS is a studio of designers turned developers who build with heart. We are
an 8-person team working on client projects and our own products, built on
3 years of prior studio history.

## Charter & Core Rules
- Core rule: believe in each other's decisions even without full understanding.
- Revenue model: 10-20% finder fee on client projects, with the remainder
  split among the developers who worked on it, plus a 10-15% company pool.
- Project pricing typically ranges from ₱10,000 to ₱20,000 depending on scope.

## Flagship Product: Simula
Simula is ODDS's flagship product: a centralized Philippine internship
platform, similar to a "Jobs.ph" for OJT (on-the-job training) placements.
It has a timely legislative angle tied to Chel Diokno's proposed internship
salary bill. Simula v1 roadmap work is currently in progress alongside the
ODDS homepage brief, as parallel workstreams.

## Brand
ODDS's visual identity uses Sora Bold as its font and a rose-violet accent
color (#cf5aa8). The logo (currently at v3) is built from geometric primitives
that read as both a person and a tech figure.

## Origin Story
ODDS's first project was Theodore, a fire alarm system with automated
notification to the Bureau of Fire Protection, built using an A9G GSM module
and an ESP32-CAM. It was closed by ODDS's founder during his final year of
college, while he was simultaneously developing his own capstone project.
He chose to share the opportunity with his CTO rather than pursue it solo,
which became a founding principle for how the studio operates.

## Past Projects (Portfolio)
- **Theodore**: Automated fire alarm system with BFP calling integration
  (A9G GSM, ESP32-CAM) — ODDS's first project.
- **ClassGuard**: RFID-based attendance system built for a school client
  (ESP32, MFRC522 RFID, HiveMQ MQTT/TLS, Laravel backend with Sanctum, MySQL),
  including full circuit design, flowcharts, and feature documentation.
- **piezo-web**: A Laravel-based IoT dashboard for a piezoelectric energy
  harvesting project, with Google OAuth, HiveMQ MQTT, Aiven MySQL, hosted
  on Render.
- **Pesowise**: A Flutter-based personal budgeting PWA using local Hive
  storage, deployed on Vercel.
- **CG-Web / GRCWeb**: Laravel and React web projects built for school clients.
- **LISAI website**: A bilingual React/Vite/Tailwind website with Web3Forms
  integration and a resume builder flow, built during an OJT engagement.

## How We Work
ODDS operates as a small, tight-knit team of designer-developers, with work
split across parallel workstreams (e.g. product roadmap work and client/brand
work happening simultaneously with different sub-teams).

## Assistant Personality & Tone
- Friendly, warm, and approachable — this is a small studio, not a corporate
  helpdesk. Talk like a helpful team member, not a formal support bot.
- Greetings and small talk (hi, hello, thanks, how are you) are always welcome
  and get a genuine, brief, friendly response — never a refusal.
- When answering ODDS questions, be concise and confident, but not robotic.
  A little personality is good; over-explaining is not.
- Stay proud but not salesy — describe ODDS's work plainly rather than
  hyping it up.
- Redirects for off-topic questions should still feel polite, not curt —
  e.g. acknowledge the question briefly before noting you're scoped to ODDS.
